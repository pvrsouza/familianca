-- Receita ou despesa que se repete (salário, condomínio, assinatura, IPVA anual). Não gera linhas: a visão anual
-- projeta as ocorrências como "previstas" até que cada uma seja confirmada (vira lançamento) ou pulada.
-- inicio/fim: competências AAAA-MM; fim nulo = sem data para acabar.
create table recorrencia (
    id          bigint generated by default as identity primary key,
    familia_id  bigint        not null references familia (id),
    categoria_id bigint       not null references categoria (id),
    membro_id   bigint        not null references membro (id),
    descricao   varchar(200)  not null,
    valor       numeric(12,2) not null check (valor > 0),
    dia         smallint      not null check (dia between 1 and 31),
    frequencia  varchar(15)   not null check (frequencia in ('MENSAL', 'BIMESTRAL', 'TRIMESTRAL', 'SEMESTRAL', 'ANUAL')),
    inicio      varchar(7)    not null check (inicio ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    fim         varchar(7)    check (fim ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    observacao  varchar(500),
    check (fim is null or fim >= inicio)
);
create index idx_recorrencia_familia on recorrencia (familia_id);

-- Ocorrências puladas (ex.: mês sem a conta).
create table recorrencia_excecao (
    recorrencia_id bigint     not null references recorrencia (id) on delete cascade,
    competencia    varchar(7) not null,
    primary key (recorrencia_id, competencia)
);

-- O que de fato entrou ou saiu. Conta no mês da data (competência = AAAA-MM da data).
-- membro_id: de quem é a receita/despesa (o impacto aparece por pessoa na visão da família).
-- recorrencia_id + competencia_recorrencia: ocorrência confirmada de uma recorrência (uma por competência).
-- parcelamento_id: compra parcelada; cada parcela é um lançamento no seu mês.
create table lancamento (
    id                      bigint generated by default as identity primary key,
    familia_id              bigint        not null references familia (id),
    categoria_id            bigint        not null references categoria (id),
    membro_id               bigint        not null references membro (id),
    descricao               varchar(200)  not null,
    valor                   numeric(12,2) not null check (valor > 0),
    data                    date          not null,
    recorrencia_id          bigint        references recorrencia (id),
    competencia_recorrencia varchar(7),
    parcelamento_id         uuid,
    parcela_numero          smallint,
    parcela_total           smallint,
    observacao              varchar(500),
    criado_em               timestamptz   not null default now(),
    check ((recorrencia_id is null) = (competencia_recorrencia is null)),
    check ((parcelamento_id is null) = (parcela_numero is null) and (parcela_numero is null) = (parcela_total is null)),
    check (parcela_numero is null or parcela_numero between 1 and parcela_total)
);
create index idx_lancamento_familia_data on lancamento (familia_id, data);
create index idx_lancamento_categoria on lancamento (categoria_id);
create index idx_lancamento_parcelamento on lancamento (parcelamento_id);
create unique index uk_lancamento_ocorrencia on lancamento (recorrencia_id, competencia_recorrencia)
    where recorrencia_id is not null;
