-- Saldo em conta no início do mês ("sobra do mês anterior"), informado pela família. Mês sem saldo informado usa
-- o fluxo de caixa líquido calculado do mês anterior.
create table saldo_mes (
    familia_id  bigint        not null references familia (id),
    competencia varchar(7)    not null check (competencia ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    valor       numeric(14,2) not null,
    observacao  varchar(200),
    primary key (familia_id, competencia)
);

-- Carteira de investimentos da família (recurso por plano).
create table investimento (
    id         bigint generated by default as identity primary key,
    familia_id bigint       not null references familia (id),
    nome       varchar(100) not null,
    tipo       varchar(20)  not null check (tipo in ('RENDA_FIXA', 'TESOURO', 'POUPANCA', 'ACOES', 'FUNDOS',
                                   'PREVIDENCIA', 'CRIPTO', 'OUTRO')),
    ativo      boolean      not null default true
);
create unique index uk_investimento_nome on investimento (familia_id, lower(nome));

-- Movimento do mês: aporte (negativo = resgate), rentabilidade do mês (%) e, opcionalmente, o saldo do extrato,
-- que prevalece sobre o calculado.
create table movimento_investimento (
    investimento_id bigint        not null references investimento (id) on delete cascade,
    competencia     varchar(7)    not null check (competencia ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    aporte          numeric(14,2) not null default 0,
    rentabilidade   numeric(9,4),
    saldo_informado numeric(14,2) check (saldo_informado >= 0),
    primary key (investimento_id, competencia)
);
