-- Plano de contas da família: tipo (receita/despesa) → grupo (com natureza fixa/variável) → categoria.
-- empresa: grupo de despesas da PJ (mostra o peso sobre as receitas tributadas).
-- Desativar esconde dos novos lançamentos e preserva o histórico; excluir só sem uso.
create table grupo_categoria (
    id         bigint generated by default as identity primary key,
    familia_id bigint      not null references familia (id),
    tipo       varchar(10) not null check (tipo in ('RECEITA', 'DESPESA')),
    natureza   varchar(10) not null check (natureza in ('FIXA', 'VARIAVEL')),
    nome       varchar(80) not null,
    empresa    boolean     not null default false,
    ordem      int         not null default 0,
    ativo      boolean     not null default true,
    check (not empresa or tipo = 'DESPESA')
);
create unique index uk_grupo_nome on grupo_categoria (familia_id, tipo, lower(nome));

-- tributavel: receita que entra na base das alíquotas da PJ (ex.: notas fiscais emitidas).
-- aliquota (%): despesa calculada = alíquota × receitas tributáveis do mês; não recebe lançamentos.
create table categoria (
    id         bigint generated by default as identity primary key,
    familia_id bigint       not null references familia (id),
    grupo_id   bigint       not null references grupo_categoria (id),
    nome       varchar(120) not null,
    ordem      int          not null default 0,
    ativa      boolean      not null default true,
    tributavel boolean      not null default false,
    aliquota   numeric(7,4) check (aliquota >= 0 and aliquota <= 100)
);
create unique index uk_categoria_nome on categoria (grupo_id, lower(nome));
create index idx_categoria_familia on categoria (familia_id);
