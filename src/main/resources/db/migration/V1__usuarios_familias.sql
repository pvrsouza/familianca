-- Quem acessa a plataforma. papel é da plataforma (ADMIN = suporte/operação; USER = cliente). O papel dentro da
-- família fica em membro. senha_hash é BCrypt; e-mail sempre em minúsculas.
create table usuario (
    id         bigint generated by default as identity primary key,
    nome       varchar(200) not null,
    email      varchar(200) not null unique,
    senha_hash varchar(100) not null,
    papel      varchar(20)  not null check (papel in ('ADMIN', 'USER')),
    ativo      boolean      not null default true,
    criado_em  timestamptz  not null default now(),
    check (email = lower(email))
);

-- Família = conta (tenant) e unidade de cobrança. Todo dado de orçamento pertence a uma família.
-- Assinatura: plano contratado, situação e validade (fim do teste ou do período pago).
create table familia (
    id                     bigint generated by default as identity primary key,
    nome                   varchar(100) not null,
    plano                  varchar(20)  not null check (plano in ('GRATUITO', 'FAMILIA', 'PREMIUM')),
    status_assinatura      varchar(20)  not null check (status_assinatura in ('TESTE', 'ATIVA', 'CANCELADA')),
    assinatura_valida_ate  date,
    meta_aporte_percentual numeric(5,2) check (meta_aporte_percentual between 0 and 100),
    criado_em              timestamptz  not null default now()
);

-- Usuário na família. Por enquanto cada usuário participa de uma única família (usuario_id único).
create table membro (
    id         bigint generated by default as identity primary key,
    familia_id bigint      not null references familia (id),
    usuario_id bigint      not null unique references usuario (id),
    papel      varchar(20) not null check (papel in ('DONO', 'MEMBRO')),
    ativo      boolean     not null default true,
    entrou_em  timestamptz not null default now()
);
create index idx_membro_familia on membro (familia_id);

-- Convite por link. Só o hash SHA-256 do token fica no banco; o token sai uma vez, na resposta de quem convidou.
create table convite (
    id           bigint generated by default as identity primary key,
    familia_id   bigint       not null references familia (id),
    email        varchar(200) not null check (email = lower(email)),
    papel        varchar(20)  not null check (papel in ('DONO', 'MEMBRO')),
    token_hash   varchar(64)  not null unique,
    status       varchar(20)  not null check (status in ('PENDENTE', 'ACEITO', 'CANCELADO')),
    expira_em    timestamptz  not null,
    convidado_por bigint      not null references membro (id),
    criado_em    timestamptz  not null default now()
);
create unique index uk_convite_pendente on convite (familia_id, email) where status = 'PENDENTE';

-- Sessões do Spring Session JDBC (schema-postgresql.sql do spring-session-jdbc 4.x), versionadas aqui porque
-- spring.session.jdbc.initialize-schema=never.
create table spring_session (
    primary_id            char(36)     not null,
    session_id            char(36)     not null,
    creation_time         bigint       not null,
    last_access_time      bigint       not null,
    max_inactive_interval int          not null,
    expiry_time           bigint       not null,
    principal_name        varchar(100),
    constraint spring_session_pk primary key (primary_id)
);
create unique index spring_session_ix1 on spring_session (session_id);
create index spring_session_ix2 on spring_session (expiry_time);
create index spring_session_ix3 on spring_session (principal_name);

create table spring_session_attributes (
    session_primary_id char(36)     not null,
    attribute_name     varchar(200) not null,
    attribute_bytes    bytea        not null,
    constraint spring_session_attributes_pk primary key (session_primary_id, attribute_name),
    constraint spring_session_attributes_fk foreign key (session_primary_id)
        references spring_session (primary_id) on delete cascade
);
