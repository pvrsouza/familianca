-- Onde está o dinheiro da família: conta corrente, poupança, dinheiro na mão, cofrinho... Cadastrado uma vez e
-- reaproveitado todo mês. Dono opcional (conta conjunta, ou de alguém sem acesso, como o cofrinho de uma criança).
create table local_saldo (
    id         bigint generated by default as identity primary key,
    familia_id bigint      not null references familia (id),
    nome       varchar(80) not null,
    tipo       varchar(20) not null check (tipo in ('CONTA_CORRENTE', 'POUPANCA', 'DINHEIRO', 'COFRINHO',
                                   'INVESTIMENTO', 'OUTRO')),
    membro_id  bigint references membro (id),
    ativo      boolean     not null default true
);
create unique index uk_local_saldo_nome on local_saldo (familia_id, lower(nome));

-- O saldo do mês item a item: o total em saldo_mes.valor é a soma destes. Mês sem itens = só o total informado.
create table saldo_mes_local (
    familia_id  bigint        not null,
    competencia varchar(7)    not null,
    local_id    bigint        not null references local_saldo (id),
    valor       numeric(14,2) not null,
    primary key (familia_id, competencia, local_id),
    foreign key (familia_id, competencia) references saldo_mes (familia_id, competencia) on delete cascade
);
create index idx_saldo_mes_local_local on saldo_mes_local (local_id);
