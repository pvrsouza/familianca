-- Verificação em duas etapas (aplicativo autenticador, TOTP), opcional por usuário. segredo_cifrado: AES-256-GCM com
-- a chave MFA_CHAVE, que fica fora do banco (um dump sozinho não gera códigos). ultimo_passo impede reusar um código.
create table mfa (
    usuario_id      bigint       primary key references usuario (id),
    segredo_cifrado varchar(500) not null,
    ativo           boolean      not null default false,
    ultimo_passo    bigint,
    criado_em       timestamptz  not null default now()
);

-- Códigos de recuperação (uso único) para quem perdeu o celular. Só o SHA-256 fica no banco.
create table mfa_codigo_recuperacao (
    id          bigint generated by default as identity primary key,
    usuario_id  bigint      not null references usuario (id),
    codigo_hash varchar(64) not null,
    usado_em    timestamptz,
    unique (usuario_id, codigo_hash)
);
