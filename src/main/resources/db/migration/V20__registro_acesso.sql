-- Registro de acesso à aplicação (Marco Civil da Internet, Lei 12.965/2014, Art. 15): um por login completo, com IP,
-- porta de origem (identifica o cliente atrás de CGNAT; vem do proxy no header X-Porta-Origem) e momento. Guardado
-- por 6 meses e apagado pela limpeza diária. Sem FK para usuario: a obrigação legal vale mesmo depois de excluída a
-- conta (LGPD Art. 16, I). Consulta só por SQL, mediante ordem judicial; não há rota na API.
-- Aditiva. Rollback: a versão anterior do app ignora a tabela.
create table registro_acesso (
    id         bigint generated by default as identity primary key,
    usuario_id bigint      not null,
    ip         varchar(45) not null,
    porta      integer     check (porta between 1 and 65535),
    momento    timestamptz not null
);
create index idx_registro_acesso_momento on registro_acesso (momento);
create index idx_registro_acesso_usuario on registro_acesso (usuario_id);
