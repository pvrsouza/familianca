-- Importação de extrato OFX/OFC. O arquivo não é guardado: só a chave de cada linha (FITID ou hash), para não
-- importar duas vezes a mesma linha. Chave única por (família, lugar do saldo, chave) no lançamento importado e,
-- para as linhas ignoradas, na tabela importacao_ignorada (sem descrição nem valor).
-- Aditiva (colunas anuláveis ou com default). Rollback: a versão anterior do app ignora as colunas e tabelas.
create table importacao_lote (
    id             bigint generated by default as identity primary key,
    familia_id     bigint      not null references familia (id),
    local_saldo_id bigint      not null references local_saldo (id) on delete cascade,
    membro_id      bigint      not null references membro (id),
    periodo_de     date        not null,
    periodo_ate    date        not null,
    importadas     integer     not null default 0,
    ignoradas      integer     not null default 0,
    confirmadas    integer     not null default 0,
    criado_em      timestamptz not null default now(),
    check (periodo_ate >= periodo_de)
);
create index idx_importacao_lote_familia on importacao_lote (familia_id, criado_em desc);

-- editado_apos_importacao: o lançamento foi alterado depois de importado; desfazer o lote não o apaga.
alter table lancamento
    add column importacao_chave          varchar(255),
    add column importacao_local_saldo_id bigint references local_saldo (id) on delete set null,
    add column importacao_lote_id        bigint references importacao_lote (id) on delete set null,
    add column editado_apos_importacao   boolean not null default false;
create unique index uk_lancamento_importacao
    on lancamento (familia_id, importacao_local_saldo_id, importacao_chave)
    where importacao_chave is not null and importacao_local_saldo_id is not null;
create index idx_lancamento_importacao_lote on lancamento (importacao_lote_id) where importacao_lote_id is not null;

create table importacao_ignorada (
    id             bigint generated by default as identity primary key,
    familia_id     bigint       not null references familia (id),
    local_saldo_id bigint       not null references local_saldo (id) on delete cascade,
    lote_id        bigint       not null references importacao_lote (id) on delete cascade,
    chave          varchar(255) not null,
    unique (familia_id, local_saldo_id, chave)
);
create index idx_importacao_ignorada_lote on importacao_ignorada (lote_id);
